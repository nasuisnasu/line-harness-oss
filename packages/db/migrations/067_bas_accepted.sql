-- 067_bas_accepted.sql — 並び替えの「別解」を許容する
--
-- 並び替えは完全一致で採点するので、答えが2通りある問題は
-- 正しく並べた生徒を不正解にしてしまう。
--
-- 第2セットではそれを避けようとして、frame に語を印字したり、
-- チップを長いかたまりにしたりして別解を潰した。**その結果、問題が易しくなった。**
--   第1セット: 1語チップ 70% / 印字ゼロの問題 89問 / 空所 平均5.6個
--   第2セット: 1語チップ 44% / 印字ゼロの問題 43問 / 空所 平均4.6個
-- 「答えを1通りにする」ために「問う量」を削ってしまった。本末転倒だった。
--
-- そこで**採点側で別解を許す**。問題は第1セットの歯ごたえに戻し、
-- 意味が変わらない別解は accepted に入れて正解にする。
--
--   accepted … JSON。並びの配列の配列。例 [["When","I meet them again","I","say","them","aloud"]]
--              NULL なら別解なし
--
-- ★ 入れてよいのは**意味が保たれる別解だけ。**
--   主語と目的語を入れ替えたようなものは入れない（それは誤答）。
ALTER TABLE bas_questions ADD COLUMN accepted TEXT;
