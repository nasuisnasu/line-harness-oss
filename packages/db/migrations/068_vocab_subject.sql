-- 単語テストに古文単語帳を足せるようにする。
--
-- 英単語帳しか無い前提で作ってあった画面が2か所ある。
--   1. 方向（英→日／日→英）。古文は「古語を見て意味を答える」向きしか出さない。
--      意味→古語の向きは、語義の文言が他の語とかぶる単語が34%あって問題が成立しない
--      （「すばらしい」に ありがたし・いみじ・めでたし… が7語ぶら下がる）。
--   2. 例文穴埋め。空所に入るのは英単語という前提の形式なので古文には無い。
--
-- subject はその出し分けだけに使う。'en' | 'kobun'。
-- 既存の2冊（ターゲット1900・シス単）は 'en' のままでよい。
ALTER TABLE vocab_books ADD COLUMN subject TEXT NOT NULL DEFAULT 'en';
