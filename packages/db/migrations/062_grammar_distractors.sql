-- 062_grammar_distractors.sql — 誤答に「どの勘違いか」のラベルを持たせる
--
-- 4択問題は生徒の頭の中についての4つの仮説。正解＝理解している、
-- 誤答3つ＝それぞれ特定の勘違い。**どの勘違いにも対応しない誤答は枠の無駄**で、
-- 誰も選ばないのでその問題は実質3択になる（`lms/grammar/02-generation.md`）。
--
-- ラベルを持たせる理由は2つ。
--   1. 生成時に「なぜそれを選ぶ人がいるのか」を書かせる縛りになる。書けない誤答は作り直し
--   2. 管理画面の「どの誤答を選んでいるか」に並べて出せる。
--      「5人中4人がこの誤答＝現在完了と since の混同」まで一目で分かる
--
-- ★ 問題を1000問作ってから足すと全部作り直しになるので、生成を始める前に入れる。

-- JSON オブジェクト。キーは choices の添字（文字列）、値は勘違いの説明。
-- 例: {"1":"仮定法だと気づかず時制を動かしていない","2":"…","3":"…"}
-- 正解の添字は含めない。未設定（NULL）でも動く。
ALTER TABLE grammar_questions ADD COLUMN distractor_notes TEXT;
